import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const handlers = {}, removed = [];
let installed;
const context = { self: { addEventListener: (name,handler)=>handlers[name]=handler, skipWaiting(){}, clients:{claim(){}} }, caches: { open: async()=>({addAll: async files=>{installed=files;}}), keys: async()=>['primary-medication-v57','primary-medication-v58','patient-system-v1','personal-os-v4'], delete: async key=>removed.push(key) } };
vm.runInNewContext(fs.readFileSync(new URL('../service-worker.js',import.meta.url),'utf8'),context);
let pending;
handlers.install({waitUntil(p){pending=p;}}); await pending;
assert.ok(installed.includes('./medication-safety.js'),'离线安装须包含新增规则');
handlers.activate({waitUntil(p){pending=p;}}); await pending;
assert.deepEqual(removed,['primary-medication-v57'],'不能清理同 GitHub Pages 域名下其他应用缓存');
console.log('离线规则预缓存及跨应用缓存隔离检查通过');
